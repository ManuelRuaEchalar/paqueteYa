-- Esquema de PaqueteYa para Postgres (Supabase). Se puede ejecutar varias veces sin romper nada.

CREATE TABLE IF NOT EXISTS puntos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- id de punto: 1, 2, 3...
  nombre      text NOT NULL,
  paqueteria  text NOT NULL,
  email       text NOT NULL UNIQUE,
  whatsapp    text NOT NULL,
  password    text NOT NULL,
  direccion   text,
  lat         double precision,
  lng         double precision,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS paquetes (
  id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  punto_id              integer NOT NULL REFERENCES puntos(id),
  numero                integer NOT NULL,
  codigo                text NOT NULL UNIQUE,
  token                 text NOT NULL UNIQUE,
  estado                text NOT NULL DEFAULT 'por_recibir',
  remitente_nombre      text NOT NULL,
  remitente_whatsapp    text NOT NULL,
  remitente_ci          text,
  destinatario_nombre   text NOT NULL,
  destinatario_whatsapp text NOT NULL,
  destinatario_ci       text,
  descripcion           text,
  moneda                text NOT NULL DEFAULT 'Bs.',
  precio                double precision,
  ubicacion             text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  recibido_at           timestamptz,
  entregado_at          timestamptz,
  UNIQUE (punto_id, numero)
);
CREATE INDEX IF NOT EXISTS idx_paquetes_punto_estado ON paquetes(punto_id, estado);

CREATE TABLE IF NOT EXISTS cajas (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  punto_id    integer NOT NULL REFERENCES puntos(id),
  nombre      text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (punto_id, nombre)
);

-- El servidor se conecta como "postgres", que ignora RLS. Activarlo sin políticas
-- cierra estas tablas a la API REST pública de Supabase (anon / authenticated).
ALTER TABLE puntos   ENABLE ROW LEVEL SECURITY;
ALTER TABLE paquetes ENABLE ROW LEVEL SECURITY;
ALTER TABLE cajas    ENABLE ROW LEVEL SECURITY;
